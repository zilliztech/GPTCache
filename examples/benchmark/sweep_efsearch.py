"""Sweep HNSW efSearch on Cell D (MRL/256/HNSW+SQ8).

Builds the index ONCE and replays the TP+FP query set across the
candidate efSearch values, so the only thing that changes between rows
is the runtime knob. Reports search-only p95 and hit rate per row.

Usage
-----
  python sweep_efsearch.py --scale 10000 --workdir sweep_work
  python sweep_efsearch.py --scale 100000 --workdir sweep_work_100k

The output is also written to ``docs/efsearch-sweep.md`` (use --out to
override). Pick the lowest ef_search that still holds the precision
threshold for your workload.
"""
import argparse
import csv
import os
import sys
import time

import numpy as np

# Reuse the harness primitives - keeps "data + encoder + ingest + measure" identical
# to the main benchmark so sweep numbers are diffable against baseline.
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from benchmark_qqp import (  # noqa: E402
    SyntheticEncoder,
    load_dataset_or_synthesise,
    setup_cell,
    ingest,
    _percentiles,
)

import faiss  # noqa: E402

EF_SEARCH_VALUES = [16, 32, 48, 64, 96, 128]
SIMILARITY_THRESH = 0.90


def measure_at_ef(encoder, data_manager, tp_queries, fp_queries, ef_search, warmup, repeats):
    evaluator = None
    from gptcache import cache as global_cache
    evaluator = global_cache.similarity_evaluation
    min_r, max_r = evaluator.range()
    rank_threshold = (max_r - min_r) * SIMILARITY_THRESH

    all_queries = list(tp_queries) + list(fp_queries)
    is_tp = [True] * len(tp_queries) + [False] * len(fp_queries)

    # Warmup with the same ef value so the path is hot
    for q in all_queries[:warmup]:
        e = encoder.to_embeddings(q)
        _ = data_manager.v.search(e, ef_search=ef_search)

    pooled = []
    tp_hits = fp_hits = 0
    for _ in range(repeats):
        for q, tp in zip(all_queries, is_tp):
            e = encoder.to_embeddings(q)
            t0 = time.perf_counter()
            res = data_manager.v.search(e, ef_search=ef_search)
            t1 = time.perf_counter()
            pooled.append((t1 - t0) * 1000.0)
            hit = False
            if res:
                dist, cid = res[0]
                score = evaluator.evaluation({}, {"search_result": (dist, cid)})
                if score >= rank_threshold:
                    hit = True
            if tp and hit:
                tp_hits += 1
            elif (not tp) and hit:
                fp_hits += 1
    perc = _percentiles(pooled)
    return {
        "ef_search": ef_search,
        "tp_rate": tp_hits / max(repeats * len(tp_queries), 1),
        "fp_rate": fp_hits / max(repeats * len(fp_queries), 1),
        **{f"search_{k}": v for k, v in perc.items()},
    }


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--scale", type=int, default=10000)
    p.add_argument("--n-tp", type=int, default=2000)
    p.add_argument("--n-fp", type=int, default=2000)
    p.add_argument("--warmup", type=int, default=20)
    p.add_argument("--repeats", type=int, default=2)
    p.add_argument("--threads", type=int, default=1)
    p.add_argument("--workdir", default="sweep_work")
    p.add_argument("--out-md", default=os.path.join("..", "..", "docs", "efsearch-sweep.md"))
    p.add_argument("--out-csv", default=None)
    args = p.parse_args()

    faiss.omp_set_num_threads(args.threads)

    encoder = SyntheticEncoder(256)
    data, source = load_dataset_or_synthesise(False, args.scale, args.n_tp, args.n_fp)
    db_q, tp_q, fp_q = data

    print(f"Sweep efSearch on Cell D (MRL/256/HNSW+SQ8), scale={args.scale}, source={source}")
    data_manager, faiss_path, sqlite_path = setup_cell(
        encoder=encoder,
        index_kind="hnsw_sq8",
        work_dir=args.workdir,
        similarity_threshold=SIMILARITY_THRESH,
        max_size=max(args.scale * 2, 100_000),
    )
    ingest_s = ingest(encoder, db_q, batch_size=64)
    print(f"Ingest: {ingest_s:.2f}s, {len(db_q)} vectors")

    rows = []
    for ef in EF_SEARCH_VALUES:
        row = measure_at_ef(encoder, data_manager, tp_q, fp_q, ef, args.warmup, args.repeats)
        print(f"  ef={ef:4d}  p50={row['search_p50']:.3f}  p95={row['search_p95']:.3f}  "
              f"p99={row['search_p99']:.3f}  TP={row['tp_rate']*100:5.2f}%  FP={row['fp_rate']*100:5.2f}%")
        rows.append(row)
    data_manager.close()

    # Write markdown
    out_md_path = args.out_md
    os.makedirs(os.path.dirname(out_md_path), exist_ok=True)
    with open(out_md_path, "w") as f:
        f.write(f"# efSearch sweep (Cell D, scale={args.scale}, threads={args.threads})\n\n")
        f.write(f"_Generated by `examples/benchmark/sweep_efsearch.py`_\n\n")
        f.write(f"Source: {source}. Encoder: synthetic-256d. FAISS {faiss.__version__}.\n\n")
        f.write("| efSearch | search p50 (ms) | search p95 (ms) | search p99 (ms) | TP% | FP% |\n")
        f.write("|---|---|---|---|---|---|\n")
        for r in rows:
            f.write(
                f"| {r['ef_search']} | {r['search_p50']:.3f} | {r['search_p95']:.3f} | "
                f"{r['search_p99']:.3f} | {r['tp_rate']*100:.2f} | {r['fp_rate']*100:.2f} |\n"
            )
        # Choose: lowest ef that holds both TP within 1 pt of the highest, and FP equally low
        max_tp = max(r["tp_rate"] for r in rows)
        chosen = next(
            (r for r in rows if (max_tp - r["tp_rate"]) <= 0.01 and r["fp_rate"] <= rows[-1]["fp_rate"]),
            rows[-1],
        )
        f.write(
            f"\n**Chosen default:** `efSearch={chosen['ef_search']}` - lowest value that holds "
            f"TP within 1 pt of the maximum observed ({max_tp*100:.2f}%) "
            f"and keeps FP at the same level as ef=128.\n\n"
            f"Run at larger scales (100K / 1M with a real encoder) to confirm before flipping "
            f"the in-code default - see `docs/runbook-real-encoders.md`.\n"
        )
    print(f"\nWrote {out_md_path}")

    if args.out_csv:
        with open(args.out_csv, "w", newline="") as f:
            w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
            w.writeheader()
            w.writerows(rows)
        print(f"Wrote {args.out_csv}")


if __name__ == "__main__":
    main()
